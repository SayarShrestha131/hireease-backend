const mongoose = require('mongoose');
require('dotenv').config();

// Connect to MongoDB
const connectDB = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ Connected to MongoDB');
  } catch (error) {
    console.error('❌ MongoDB connection error:', error);
    process.exit(1);
  }
};

// Vehicle Schema
const vehicleSchema = new mongoose.Schema({
  name: String,
  brand: String,
  vehicleModel: String,
  year: Number,
  category: String,
  transmission: String,
  fuelType: String,
  seatingCapacity: Number,
  pricePerDay: Number,
  images: [String],
  features: [String],
  availability: {
    isAvailable: Boolean,
    nextAvailableDate: Date,
  },
  specifications: {
    engineCapacity: String,
    mileage: String,
    color: String,
  },
  location: String,
  description: String,
  rating: Number,
  totalReviews: Number,
  createdAt: Date,
  updatedAt: Date,
});

const Vehicle = mongoose.model('Vehicle', vehicleSchema);

